#!/usr/bin/env python3
# Usage: python3 scripts/dev/iam-theme-board.py helm/classifyre/files/iam/theme/login/resources/img/board.svg
#
# Generates the sign-in backdrop from the landing's string board
# (apps/blog/components/closing-board.tsx): same pins, threads and finding
# labels, animated in CSS inside the SVG so the theme needs no script.
import sys
PINS=[(70,80),(215,195),(140,365),(335,110),(465,250),(415,435),(600,130),(705,320),(620,455),(815,175),(905,365),(950,95)]
TAGGED=[0,2,3,4,6,7,9]
THREADS=[(0,1),(0,3),(1,4),(2,1),(2,5),(3,4),(4,6),(4,7),(5,7),(5,8),(6,9),(7,9),(7,10),(8,10),(9,11)]
TAGS=["leaked email","credit card","invalid balance","exposed secret","wrong address","leaked credential","insolvency","unpaid invoice","expired contract","sanctioned entity","stale export","orphaned account","missing consent","duplicate vendor"]
TICK=4.2; N=len(TAGS); CYCLE=TICK*N
win=100/N
o=[]
o.append('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 520" preserveAspectRatio="xMidYMid slice">')
o.append('<!-- The landing\'s string board (apps/blog/components/closing-board.tsx): evidence pins joined by dashed threads, labels rotating through findings. Generated by scripts/dev/iam-theme-board.py; keep the geometry in step with the landing. -->')
o.append(f'''<style>
.b{{animation:d 26s ease-in-out infinite alternate;transform-origin:50% 50%}}
@keyframes d{{from{{transform:scale(1.05) translate(0,0)}}to{{transform:scale(1.05) translate(-1.5%,1%)}}}}
.t{{stroke:#fff;stroke-opacity:.16;stroke-width:1.5;stroke-dasharray:6 7;animation:f 10s linear infinite}}
@keyframes f{{to{{stroke-dashoffset:-130}}}}
.p{{fill:#b7ff00;animation:g 4.5s ease-in-out infinite}}
@keyframes g{{0%,100%{{opacity:.3}}50%{{opacity:1}}}}
.l{{fill:#fff;font:13px ui-monospace,SFMono-Regular,Menlo,monospace;letter-spacing:.14em;opacity:0;animation:c {CYCLE:.1f}s linear infinite}}
@keyframes c{{0%{{opacity:0;transform:translateY(5px)}}{win*0.15:.2f}%{{opacity:.3;transform:none}}{win*0.95:.2f}%{{opacity:.3}}{win:.2f}%,100%{{opacity:0}}}}
@media (prefers-reduced-motion:reduce){{.b,.t,.p,.l{{animation:none}}.p{{opacity:.6}}.l.z{{opacity:.3}}}}
</style>''')
o.append('<rect width="1000" height="520" fill="#0a0a0a"/><g class="b">')
for a,b in THREADS:
    (x1,y1),(x2,y2)=PINS[a],PINS[b]
    o.append(f'<line class="t" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
for i,(x,y) in enumerate(PINS):
    o.append(f'<rect class="p" x="{x-6}" y="{y-6}" width="12" height="12" style="animation-delay:{i*0.38:.2f}s"/>')
    if i in TAGGED:
        s=TAGGED.index(i)
        for j,tag in enumerate(TAGS):
            t=(j-5*s)%N
            cls="l z" if t==0 else "l"
            o.append(f'<text class="{cls}" x="{x+12}" y="{y+4}" style="animation-delay:{t*TICK:.1f}s">{tag}</text>')
o.append('</g></svg>')
open(sys.argv[1],"w").write("\n".join(o)+"\n")
